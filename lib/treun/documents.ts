// Printable procurement documents, generated in the browser from an order.
// Each opens in a new tab as a styled page; use the browser's Print → Save as PDF to export.
import { SUPPLIERS } from "./catalog";

export interface DocOrder {
  id: string;
  time: string;
  unit: string;
  request: string;
  budgetUsdc: number;
  totalUsdc: number;
  settledUsdc: number;
  status: "quoted" | "paid" | "refused";
  reason?: string;
  signature?: string;
  lines: { itemId?: string; name: string; supplier: string; country?: string; qty: number; unitPriceUsdc?: number; lineTotalUsdc: number }[];
}

const esc = (s: unknown) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);
const money = (n: number) => `${n.toLocaleString(undefined, { maximumFractionDigits: 2 })} USDC`;
const date = (iso: string) => new Date(iso).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" });
const supplier = (name: string) => SUPPLIERS.find((s) => s.name === name);
const suppliersOf = (o: DocOrder) => [...new Set(o.lines.map((l) => l.supplier))];

function page(title: string, ref: string, body: string) {
  return `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)} ${esc(ref)}</title>
<style>
  @page { size: A4; margin: 18mm; }
  body { font: 13px/1.5 "Helvetica Neue", Arial, sans-serif; color: #12151A; background: #EDE9E1; margin: 0; }
  .sheet { max-width: 800px; margin: 24px auto; background: #fff; padding: 40px 48px; border: 1px solid #D8D3C8; }
  header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 3px solid #12151A; padding-bottom: 14px; margin-bottom: 20px; }
  .brand { font-size: 26px; font-weight: 800; letter-spacing: -0.04em; }
  .brand small { display: block; font-size: 10px; letter-spacing: 0.08em; text-transform: uppercase; color: #7C828C; font-weight: 600; }
  h1 { margin: 0; font-size: 20px; text-align: right; } h1 small { display: block; font-size: 12px; color: #B67A45; font-weight: 600; }
  h2 { font-size: 12px; text-transform: uppercase; letter-spacing: 0.06em; color: #7C828C; margin: 22px 0 6px; }
  table { width: 100%; border-collapse: collapse; margin-top: 6px; }
  th { text-align: left; font-size: 11px; text-transform: uppercase; color: #7C828C; border-bottom: 1px solid #12151A; padding: 6px 4px; }
  td { padding: 7px 4px; border-bottom: 1px solid #E5E0D6; vertical-align: top; } td.n, th.n { text-align: right; }
  .total td { font-weight: 800; border-bottom: 2px solid #12151A; }
  .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px 28px; }
  .kv b { display: block; font-size: 11px; text-transform: uppercase; color: #7C828C; letter-spacing: 0.04em; }
  .ok { color: #12151A; } .bad { color: #A23B2A; font-weight: 700; }
  .note { margin-top: 22px; padding: 10px 12px; background: #F3EBDD; border-left: 3px solid #B67A45; font-size: 12px; }
  .sig { display: grid; grid-template-columns: 1fr 1fr; gap: 28px; margin-top: 34px; } .sig div { border-top: 1px solid #12151A; padding-top: 6px; font-size: 11px; color: #7C828C; }
  code { font: 11px ui-monospace, Menlo, monospace; word-break: break-all; }
  .bar { max-width: 800px; margin: 16px auto 0; text-align: right; } .bar button { font: 700 13px sans-serif; padding: 10px 18px; border-radius: 999px; border: 0; background: #12151A; color: #EDE9E1; cursor: pointer; }
  @media print { body { background: #fff; } .sheet { border: 0; margin: 0; padding: 0; } .bar { display: none; } }
</style></head><body>
<div class="bar"><button onclick="window.print()">Print / Save as PDF</button></div>
<div class="sheet">
<header><div class="brand">treun<small>Agentic procurement ledger</small></div><h1>${esc(title)}<small>${esc(ref)}</small></h1></header>
${body}
<div class="note">Demo document generated by Treun. Suppliers and products are fictional and licence checks are simulated. Payment amounts on Solana devnet are test USDC, scaled to order value ÷ 10,000.</div>
</div></body></html>`;
}

function linesTable(o: DocOrder) {
  const rows = o.lines
    .map((l, i) => `<tr><td>${i + 1}</td><td>${esc(l.itemId ?? "")}</td><td>${esc(l.name)}</td><td>${esc(l.supplier)}</td><td class="n">${l.qty}</td><td class="n">${l.unitPriceUsdc ? money(l.unitPriceUsdc) : ""}</td><td class="n">${money(l.lineTotalUsdc)}</td></tr>`)
    .join("");
  return `<table><thead><tr><th>#</th><th>Cat. no.</th><th>Description</th><th>Supplier</th><th class="n">Qty</th><th class="n">Unit price</th><th class="n">Line total</th></tr></thead>
<tbody>${rows}<tr class="total"><td colspan="6">Total</td><td class="n">${money(o.totalUsdc)}</td></tr></tbody></table>`;
}

export function rfqDoc(o: DocOrder) {
  const due = new Date(new Date(o.time).getTime() + 3 * 864e5).toISOString();
  return page("Request for Quotation", `RFQ-${o.id}`, `
<div class="grid">
  <div class="kv"><b>Issued by</b>${esc(o.unit)}</div>
  <div class="kv"><b>Issued</b>${date(o.time)}</div>
  <div class="kv"><b>Addressed to</b>${suppliersOf(o).map(esc).join("<br>")}</div>
  <div class="kv"><b>Respond by</b>${date(due)}</div>
</div>
<h2>Requirement</h2><p>${esc(o.request)}</p>
<h2>Items requested</h2>${linesTable(o)}
<h2>Terms</h2>
<ul>
  <li>Prices in USDC, settled on Solana on acceptance of the purchase order.</li>
  <li>Suppliers must hold a valid export licence for every item quoted; licence references are checked before payment.</li>
  <li>Budget ceiling for this requirement: ${money(o.budgetUsdc)}.</li>
  <li>Quotes are recorded on the Treun audit ledger with this reference.</li>
</ul>
<div class="sig"><div>Authorised by (unit procurement officer)</div><div>Date</div></div>`);
}

export function complianceDoc(o: DocOrder) {
  const rows = suppliersOf(o)
    .map((n) => {
      const s = supplier(n);
      const ok = s?.licence.status === "valid";
      return `<tr><td>${esc(n)}</td><td>${esc(s?.country ?? "")}</td><td><code>${esc(s?.licence.ref ?? "")}</code></td><td>${esc(s?.licence.expires ?? "")}</td><td class="${ok ? "ok" : "bad"}">${ok ? "Valid" : "EXPIRED"}</td></tr>`;
    })
    .join("");
  const overBudget = o.totalUsdc > o.budgetUsdc;
  return page("Compliance Check Record", `CMP-${o.id}`, `
<div class="grid">
  <div class="kv"><b>Order reference</b>${esc(o.id)}</div>
  <div class="kv"><b>Checked</b>${date(o.time)}</div>
  <div class="kv"><b>Buyer</b>${esc(o.unit)}</div>
  <div class="kv"><b>Outcome</b><span class="${o.status === "refused" ? "bad" : "ok"}">${o.status === "refused" ? "REFUSED" : "PASSED"}</span>${o.reason ? `: ${esc(o.reason)}` : ""}</div>
</div>
<h2>Supplier licence checks</h2>
<table><thead><tr><th>Supplier</th><th>Country</th><th>Licence ref.</th><th>Expires</th><th>Status</th></tr></thead><tbody>${rows}</tbody></table>
<h2>Budget check</h2>
<table><tbody>
<tr><td>Order total</td><td class="n">${money(o.totalUsdc)}</td></tr>
<tr><td>Unit budget</td><td class="n">${money(o.budgetUsdc)}</td></tr>
<tr class="total"><td>Result</td><td class="n ${overBudget ? "bad" : "ok"}">${overBudget ? "Over budget" : "Within budget"}</td></tr>
</tbody></table>
<h2>Items</h2>${linesTable(o)}`);
}

export function purchaseOrderDoc(o: DocOrder) {
  const paid = o.status === "paid";
  return page(paid ? "Purchase Order & Payment Receipt" : "Draft Purchase Order", `PO-${o.id}`, `
<div class="grid">
  <div class="kv"><b>Buyer</b>${esc(o.unit)}</div>
  <div class="kv"><b>Date</b>${date(o.time)}</div>
  <div class="kv"><b>Supplier(s)</b>${suppliersOf(o).map((n) => `${esc(n)} (${esc(supplier(n)?.country ?? "")})`).join("<br>")}</div>
  <div class="kv"><b>Status</b>${paid ? "Paid and recorded on-chain" : "Awaiting buyer confirmation (not paid)"}</div>
</div>
<h2>Order</h2>${linesTable(o)}
<h2>Payment</h2>
<table><tbody>
<tr><td>Currency</td><td class="n">USDC on Solana</td></tr>
<tr><td>Order value</td><td class="n">${money(o.totalUsdc)}</td></tr>
<tr><td>Devnet test settlement</td><td class="n">${money(o.settledUsdc)}</td></tr>
${paid && o.signature ? `<tr><td>Transaction</td><td class="n"><code>${esc(o.signature)}</code></td></tr><tr><td>Verify</td><td class="n"><code>https://explorer.solana.com/tx/${esc(o.signature)}?cluster=devnet</code></td></tr>` : ""}
</tbody></table>
<div class="sig"><div>Authorised by (buyer)</div><div>Accepted by (supplier)</div></div>`);
}

export function endUserDoc(o: DocOrder) {
  return page("End-User Undertaking (Draft)", `EUU-${o.id}`, `
<p>We, <b>${esc(o.unit)}</b>, the end user of the goods listed below, undertake that:</p>
<ol>
  <li>The goods will be used only by the end user named above, for the stated purpose.</li>
  <li>The goods will not be re-exported, transferred or resold without the prior written authorisation of the exporting government.</li>
  <li>The goods will not be used in connection with weapons of mass destruction or in breach of any arms embargo.</li>
  <li>We will permit post-shipment verification by the exporting authority on request.</li>
</ol>
<h2>Goods</h2>${linesTable(o)}
<h2>Exporters</h2><p>${suppliersOf(o).map((n) => `${esc(n)} — licence ${esc(supplier(n)?.licence.ref ?? "")}`).join("<br>")}</p>
<div class="sig"><div>Signed for the end user</div><div>Official stamp and date</div></div>`);
}

export function openDoc(html: string) {
  const url = URL.createObjectURL(new Blob([html], { type: "text/html" }));
  window.open(url, "_blank", "noopener");
}
